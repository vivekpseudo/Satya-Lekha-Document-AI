"""Generate the rule reference (docs/RULES.md) and rule metadata files from the code.

The rules live in code; this keeps the written catalogue from drifting away from
them. Run ``python -m app.rule_docs`` after adding or renaming a rule. A test
fails if the generated files are out of date.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from app.cash_flow_rules import CASH_FLOW_STATEMENT_RULES
from app.cross_rules import CROSS_RULES
from app.notice_invoice_rules import NOTICE_INVOICE_RULES
from app.rule_registry import RULE_REGISTRY
from app.rules_engine import DEFAULT_RULES
from app.statement_rules import STATEMENT_RULES
from app.text_rules import TEXT_RULES

ROOT = Path(__file__).resolve().parent.parent
RULES_MD = ROOT / "docs" / "RULES.md"
CATALOG_JSON = ROOT / "app" / "rule_catalog.json"
MANIFEST_JSON = ROOT / "regulatory" / "rules" / "manifest.json"

# (id prefix, heading, what the family covers)
FAMILIES = [
    ("INDAS-FS", "Balance sheet equation (original rule)",
     "Total assets against total liabilities plus equity, current year."),
    ("DATA-QUALITY", "Data quality",
     "A heuristic, not a regulatory requirement."),
    ("FSBS", "Balance sheet",
     "Both-year balance, sub-totals, line items, Schedule III headings, comparatives, note totals, "
     "signatures and UDIN."),
    ("FSPL", "Statement of profit and loss",
     "Schedule III headings, expense totals, profit before and after tax, earnings per share."),
    ("FSX", "Across the statements", "Links between the balance sheet and the statement of profit and loss."),
    ("CFS", "Cash flow statement (AS 3 / Ind AS 7)",
     "Structure, arithmetic in both years, continuity, and agreement with the other statements."),
    ("DIRREP", "Directors' Report (Companies Act ss.92, 134, 173)",
     "Required disclosures, Board meetings, annual return, signatures and dating."),
    ("AUDREP", "Auditor's Report (SA 700, s.143, CARO)",
     "Opinion and its basis, responsibilities, other legal requirements, CARO version, signature and UDIN."),
    ("NOTICE", "AGM notice (ss.96, 101, 102, 105, 139, SS-2)",
     "Meeting details and timing, notice period, business, auditor appointment, proxies, issuer."),
    ("INV", "Invoice (CGST Rule 46)",
     "Number and date, recipient, GST particulars, GSTIN check digit, PAN, arithmetic, amount in words, signature."),
    ("XDOC", "Cross-document checks",
     "Compare the Directors' Report, Auditor's Report, statements, notice and invoice with each other."),
]

DOCUMENT_TYPES = {
    "balance_sheet": "balance sheet", "profit_and_loss": "profit and loss", "cash_flow": "cash flow",
    "directors_report": "Directors' Report", "auditors_report": "Auditor's Report",
    "agm_notice": "AGM notice", "invoice": "invoice", "other": "other",
}


def _family(rule_id: str) -> str:
    return re.match(r"[A-Z]+(?:-[A-Z]+)?", rule_id).group(0)


def collect() -> list[dict]:
    """Every rule, in the order the engines run them."""
    rules: list[dict] = []
    for group in (DEFAULT_RULES, STATEMENT_RULES, CASH_FLOW_STATEMENT_RULES, TEXT_RULES, NOTICE_INVOICE_RULES):
        for rule in group:
            rules.append({"rule_id": rule.rule_id, "title": rule.title,
                          "document_types": sorted(rule.statement_types)})
    for rule_id, title, _ in CROSS_RULES:
        rules.append({"rule_id": rule_id, "title": title, "document_types": ["package"]})
    for rule in rules:
        meta = RULE_REGISTRY.get(rule["rule_id"])
        rule["family"] = _family(rule["rule_id"])
        rule["regulators"] = list(meta.regulators) if meta else []
        rule["frameworks"] = list(meta.frameworks) if meta else []
    return rules


def _applies_to(types: list[str]) -> str:
    if types == ["package"]:
        return "two or more documents"
    return ", ".join(DOCUMENT_TYPES.get(t, t) for t in types)


def render_markdown(rules: list[dict]) -> str:
    out = [
        "# Rule reference",
        "",
        "<!-- Generated by `python -m app.rule_docs`. Do not edit by hand. -->",
        "",
        f"{len(rules)} deterministic rules. Each returns `PASS`, `FAIL` or `REVIEW`, with the text or figures it "
        "relied on and a confidence. Document-specific rules stay silent on other document types.",
        "",
        "A passing result means a document is internally consistent or agrees with the others. It does not mean "
        "the document is correct. The legal references come from the authors' reading of the Companies Act, 2013, "
        "the Standards on Auditing, the CGST Rules and AS 3 / Ind AS 7; they have not been reviewed by a "
        "qualified professional and should be confirmed before anyone relies on a finding.",
        "",
        "How to read it: a `FAIL` means the rule's condition is not met. A `REVIEW` means a person should look, "
        "because the evidence is incomplete or there may be an innocent explanation.",
        "",
    ]
    for prefix, heading, blurb in FAMILIES:
        members = [r for r in rules if r["family"] == prefix]
        if not members:
            continue
        out += [f"## {heading}", "", blurb, "", "| Rule | Check | Applies to |", "|---|---|---|"]
        for r in members:
            out.append(f"| `{r['rule_id']}` | {r['title']} | {_applies_to(r['document_types'])} |")
        out.append("")
    return "\n".join(out)


def render_catalog(rules: list[dict]) -> str:
    catalog = {"version": "0.2.0", "jurisdiction": "IN", "generated_by": "python -m app.rule_docs",
               "rules": [{"rule_id": r["rule_id"], "title": r["title"], "family": r["family"],
                          "document_types": r["document_types"], "regulators": r["regulators"],
                          "frameworks": r["frameworks"]} for r in rules]}
    return json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"


def render_manifest(rules: list[dict]) -> str:
    manifest = {"schema_version": "0.2.0", "jurisdiction": "IN", "generated_by": "python -m app.rule_docs",
                "rules": [{"rule_id": r["rule_id"], "regulators": r["regulators"], "framework": r["frameworks"],
                           "status": "heuristic" if r["family"] == "DATA-QUALITY" else "implemented",
                           "source_status": "non-regulatory" if r["family"] == "DATA-QUALITY"
                           else "needs_authoritative_ingestion"} for r in rules]}
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def render_all() -> dict[Path, str]:
    rules = collect()
    return {RULES_MD: render_markdown(rules) + "\n", CATALOG_JSON: render_catalog(rules),
            MANIFEST_JSON: render_manifest(rules)}


def main(argv: list[str]) -> int:
    outputs = render_all()
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("Out of date (run `python -m app.rule_docs`): " + ", ".join(stale))
            return 1
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
